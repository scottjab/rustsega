/// octave, the `4.8` of a 13-bit sum of [`LOGSIN`] and the envelope times four,
/// and turning it back into a linear amplitude takes the top eight bits as a
/// shift and the low eight as an index here. The full 11-bit mantissa is
/// `EXP[i] | 0x400`, which is why the entries stop at `0x3fa` rather than
